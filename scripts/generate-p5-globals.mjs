#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const P5_BUILD = path.join(ROOT, 'vendor/p5/1.9.0/p5.min.js');
export const P5_SOUND_BUILD = path.join(ROOT, 'vendor/p5/1.9.0/p5.sound.min.js');
export const OUTPUT = path.join(ROOT, 'src/core/validators/p5Globals.generated.ts');

export const DENYLIST = {
  constructor: 'JavaScript constructor slot, not a sketch-callable name',
  registerMethod: 'library-extension hook, not sketch API',
  registerPreloadMethod: 'library-extension hook, not sketch API',
  registerPromisePreload: 'library-extension hook, not sketch API',
  unregisterMethod: 'library-extension hook, not sketch API',
};

const WEB_AUDIO_STUB = `(() => {
  const any = () => new Proxy(function () {}, {
    get: (_t, k) => (k === Symbol.toPrimitive ? () => 0 : k === 'then' ? undefined : any()),
    apply: () => any(),
    construct: () => any(),
    set: () => true,
  });
  window.AudioContext = function () { return any(); };
  window.webkitAudioContext = window.AudioContext;
  window.OfflineAudioContext = window.AudioContext;
  window.AudioWorkletNode = function () { return any(); };
  window.AudioNode = function () {};
  window.AudioParam = function () {};
  window.Worker = function () { return any(); };
  window.URL.createObjectURL = () => 'blob:stub';
})();`;

export function collectP5Globals(buildPath = P5_BUILD, soundBuildPath = P5_SOUND_BUILD) {
  const dom = new JSDOM('<!doctype html><body></body>', { runScripts: 'outside-only' });
  try {
    dom.window.eval(fs.readFileSync(buildPath, 'utf8'));
    dom.window.eval(WEB_AUDIO_STUB);
    dom.window.eval(fs.readFileSync(soundBuildPath, 'utf8'));
    const { p5 } = dom.window;
    const names = new Set();
    for (let proto = p5.prototype; proto && proto !== dom.window.Object.prototype; proto = Object.getPrototypeOf(proto)) {
      for (const name of Object.getOwnPropertyNames(proto)) names.add(name);
    }
    return {
      version: p5.VERSION,
      names: [...names].filter((n) => !n.startsWith('_') && !(n in DENYLIST)).sort(),
    };
  } finally {
    dom.window.close();
  }
}

export function renderGenerated({ version, names }) {
  return [
    `// Generated by scripts/generate-p5-globals.mjs from vendor/p5/${version}/p5.min.js + p5.sound.min.js (p5 ${version}). Do not edit.`,
    'export const P5_GENERATED_GLOBALS: readonly string[] = [',
    ...names.map((n) => `  '${n}',`),
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUTPUT, renderGenerated(collectP5Globals()));
}
